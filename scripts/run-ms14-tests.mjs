import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectPath = dirname(scriptDirectory);
const outputPath = join(projectPath, '.test-build');
const localCompilerPath = join(projectPath, 'node_modules', 'typescript', 'bin', 'tsc');
const html = readFileSync(join(projectPath, 'index.html'), 'utf8');
const main = readFileSync(join(projectPath, 'src', 'main.ts'), 'utf8');
const renderer = readFileSync(join(projectPath, 'src', 'engine', 'renderer', 'CanvasRenderer.ts'), 'utf8');
assert(html.includes('id="satellite-count-input"'), 'Satellite settlement count input is missing.');
assert(html.includes('id="cancel-generation-button"'), 'Generation cancellation control is missing.');
assert(html.includes('id="generation-progress"'), 'Generation progress UI is missing.');
assert(html.includes('id="perf-generation-total"'), 'Performance diagnostics panel is missing.');
assert(main.includes('generationWorker.generate'), 'Worker-backed full-world generation is not integrated into the editor.');
assert(existsSync(join(projectPath, 'src', 'workers', 'generation.worker.ts')), 'Generation worker entry point is missing.');
assert(existsSync(join(projectPath, 'src', 'browser', 'GenerationWorkerClient.ts')), 'Generation worker client is missing.');
assert(main.includes('rasterCacheLayersForStage'), 'Stage-aware raster cache invalidation is not integrated.');
assert(renderer.includes('SpatialGridIndex'), 'Viewport spatial indexing is not enabled in the renderer.');
rmSync(outputPath, { recursive: true, force: true });
if (existsSync(localCompilerPath)) execFileSync(process.execPath, [localCompilerPath, '-p', 'tsconfig.test.json'], { cwd: projectPath, stdio: 'inherit' });
else execFileSync('tsc', ['-p', 'tsconfig.test.json'], { cwd: projectPath, stdio: 'inherit' });
writeFileSync(join(outputPath, 'package.json'), '{"type":"commonjs"}\n');
execFileSync(process.execPath, [join(outputPath, 'tests', 'Milestone14Test.js')], { cwd: projectPath, stdio: 'inherit' });
